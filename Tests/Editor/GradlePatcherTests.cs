using AdfactenAds.Editor;
using NUnit.Framework;

namespace AdfactenAds.Tests
{
    public class GradlePatcherTests
    {
        private const string Repo = "https://cdn.adfacten.com/maven/";

        // Unity 2022.2+ settings.gradle.
        private const string Settings2022 = @"pluginManagement {
    repositories {
        gradlePluginPortal()
        google()
        mavenCentral()
    }
}

include ':launcher', ':unityLibrary'

dependencyResolutionManagement {
    repositoriesMode.set(RepositoriesMode.PREFER_SETTINGS)
    repositories {
        google()
        mavenCentral()
        flatDir {
            dirs ""${project(':unityLibrary').projectDir}/libs""
        }
    }
}
";

        // Unity 2021.3 root build.gradle.
        private const string Root2021 = @"// GENERATED BY UNITY. { not a block }
allprojects {
    buildscript {
        repositories {
            google()
            jcenter()
        }
        dependencies {
            classpath 'com.android.tools.build:gradle:4.0.1'
        }
    }

    repositories {
        google()
        jcenter()
        flatDir {
            dirs ""${project(':unityLibrary').projectDir}/libs""
        }
    }
}

task clean(type: Delete) {
    delete rootProject.buildDir
}
";

        private const string UnityLibrary = @"apply plugin: 'com.android.library'

dependencies {
    implementation fileTree(dir: 'libs', include: ['*.jar'])
    implementation 'com.adfacten:ads-video:1.0.2'
}

android {
    compileSdkVersion 34
}
";

        [Test]
        public void AddsTheRepositoryToDependencyResolutionManagement()
        {
            var patched = GradlePatcher.AddRepository(Settings2022, Repo);
            var drm = patched.IndexOf("dependencyResolutionManagement");
            var repo = patched.IndexOf(Repo);
            Assert.Greater(repo, drm, "not in pluginManagement");
            Assert.Less(repo, patched.IndexOf("google()", drm));
            Assert.AreEqual(patched, GradlePatcher.AddRepository(patched, Repo), "idempotent");
        }

        [Test]
        public void AddsTheRepositoryToAllprojectsNotBuildscript()
        {
            var patched = GradlePatcher.AddRepository(Root2021, Repo);
            var repo = patched.IndexOf(Repo);
            Assert.Greater(repo, patched.IndexOf("classpath"), "not in buildscript");
            Assert.Less(repo, patched.IndexOf("task clean"));
        }

        [Test]
        public void NoRepositoriesBlockReturnsNull()
        {
            Assert.IsNull(GradlePatcher.AddRepository(UnityLibrary, Repo));
        }

        [Test]
        public void DetectsDependenciesByExactArtifact()
        {
            Assert.IsTrue(GradlePatcher.HasDependency(UnityLibrary, "com.adfacten:ads-video"));
            Assert.IsFalse(GradlePatcher.HasDependency(UnityLibrary, "com.adfacten:ads"), "ads-video is not ads");
            Assert.IsTrue(GradlePatcher.HasDependency("implementation \"com.adfacten:ads:1.0.2\"", "com.adfacten:ads"));
        }

        [Test]
        public void AddsDependenciesToTheTopLevelBlock()
        {
            var patched = GradlePatcher.AddDependencies(UnityLibrary, new[] { "com.adfacten:ads:1.0.2" });
            Assert.IsTrue(GradlePatcher.HasDependency(patched, "com.adfacten:ads"));
            Assert.Less(patched.IndexOf("com.adfacten:ads:1.0.2"), patched.IndexOf("android {"));
            var noBlock = GradlePatcher.AddDependencies("apply plugin: 'x'\n", new[] { "com.adfacten:ads:1.0.2" });
            StringAssert.Contains("dependencies {\n    implementation 'com.adfacten:ads:1.0.2'", noBlock);
        }

        [Test]
        public void IgnoresBracesInCommentsAndStrings()
        {
            var text = "/* allprojects { repositories { */\nx = '}'\nallprojects {\n  repositories {\n  }\n}\n";
            var i = GradlePatcher.FindBlock(text, new[] { "allprojects", "repositories" });
            Assert.AreEqual(text.IndexOf("repositories {\n  }") + "repositories ".Length, i);
        }

        [Test]
        public void RemovesTheAdIdPermission()
        {
            const string manifest = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<manifest xmlns:android=\"http://schemas.android.com/apk/res/android\" package=\"com.unity3d.player\">\n  <application />\n</manifest>\n";
            var patched = GradlePatcher.RemoveAdIdPermission(manifest);
            StringAssert.Contains("xmlns:tools=\"http://schemas.android.com/tools\"", patched);
            StringAssert.Contains("android:name=\"com.google.android.gms.permission.AD_ID\" tools:node=\"remove\"", patched);
            Assert.AreEqual(patched, GradlePatcher.RemoveAdIdPermission(patched), "idempotent");
            var doc = new System.Xml.XmlDocument();
            Assert.DoesNotThrow(() => doc.LoadXml(patched));
        }
    }
}
